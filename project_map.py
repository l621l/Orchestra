"""Bounded, non-executing Python interface inventory from current source."""
import ast
import hashlib
import os
from pathlib import Path
import tempfile
from interface_notes import InterfaceNotes

HEADER = '# PROJECT_MAP — generated by Orchestra; do not edit manually\n'


def short(node, limit=120):
    text = ast.unparse(node) if node is not None else '?'
    text = ' '.join(text.split())
    return text if len(text)<=limit else text[:limit-3]+'...'


def signature(node):
    # Defaults represented by large literals must not flood the context.
    return '('+short(node.args, 170)+')' + (' -> '+short(node.returns,60) if node.returns else '')


def describe(path, tree, digest):
    classes, functions, imports, variables = [], [], [], []
    for node in tree.body:
        if isinstance(node,(ast.Assign,ast.AnnAssign)):
            targets=node.targets if isinstance(node,ast.Assign) else [node.target]
            for target in targets:
                if isinstance(target,ast.Name) and not target.id.startswith('_'):
                    annotation=short(node.annotation,60) if isinstance(node,ast.AnnAssign) else 'module variable'
                    variables.append(f'{target.id}: {annotation} @{node.lineno}')
        if isinstance(node,(ast.Import,ast.ImportFrom)):
            imports.append(short(node,160))
        if isinstance(node,ast.ClassDef):
            fields = {}
            methods = []
            for item in node.body:
                if isinstance(item,ast.AnnAssign) and isinstance(item.target,ast.Name):
                    fields[item.target.id] = short(item.annotation,60)
                elif isinstance(item,ast.Assign):
                    for target in item.targets:
                        if isinstance(target,ast.Name) and not target.id.startswith('__'):
                            fields.setdefault(target.id,'class attribute')
                if isinstance(item,(ast.FunctionDef,ast.AsyncFunctionDef)):
                    methods.append(f'  {item.name}{signature(item)} @{item.lineno}')
                    # self fields only in this method, excluding nested functions/classes.
                    pending = list(item.body)
                    while pending:
                        child = pending.pop()
                        if isinstance(child,(ast.FunctionDef,ast.AsyncFunctionDef,ast.ClassDef,ast.Lambda)):
                            continue
                        targets = child.targets if isinstance(child,ast.Assign) else [child.target] if isinstance(child,ast.AnnAssign) else []
                        for target in targets:
                            if isinstance(target,ast.Attribute) and isinstance(target.value,ast.Name) and target.value.id=='self':
                                fields.setdefault(target.attr,short(child.annotation,60) if isinstance(child,ast.AnnAssign) else 'assigned on self')
                        pending.extend(ast.iter_child_nodes(child))
            bases = ', '.join(short(b,60) for b in node.bases)
            classes.append(f'class {node.name}({bases}) @{node.lineno}\n  fields: '+
                (', '.join(f'{key}: {value}' for key,value in sorted(fields.items())) or '(none statically declared)')+
                ('\n'+'\n'.join(methods) if methods else ''))
        if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef)):
            functions.append(f'def {node.name}{signature(node)} @{node.lineno}')
    return {'path':path, 'digest':digest, 'classes':classes, 'functions':functions, 'imports':imports,'variables':variables}


class ProjectMap:
    def __init__(self, policy, max_files=200):
        self.policy = policy
        self.root = policy.root
        self.max_files = max_files
        self.cache = {}
        self.notes = InterfaceNotes(policy)
        self.focus_paths = []

    def refresh(self, context_limit=6000):
        records, skipped = [], 0
        candidates = []
        for current, dirs, files in os.walk(self.root, followlinks=False):
            relative = Path(current).relative_to(self.root)
            dirs[:] = sorted(name for name in dirs if self.policy.parts_allowed((*relative.parts,name))
                              and not (Path(current)/name).is_symlink())
            for name in sorted(files):
                if name.endswith('.py') and self.policy.parts_allowed((*relative.parts,name)):
                    candidates.append((Path(current)/name).relative_to(self.root).as_posix())
                    if len(candidates)>self.max_files: break
            if len(candidates)>self.max_files:
                break
        # Production definitions before tests; deterministic selection.
        candidates.sort(key=lambda name:(name not in self.focus_paths, name.startswith('tests/') or Path(name).name.startswith('test_'),name))
        skipped += max(0,len(candidates)-self.max_files)
        for relative in candidates[:self.max_files]:
            try:
                source = self.policy.resolve_read(relative)
                if source.stat().st_size>500000:
                    skipped += 1
                    continue
                raw = source.read_bytes()
                digest = hashlib.sha256(raw).hexdigest()
                cached = self.cache.get(relative)
                if cached and cached['digest']==digest:
                    records.append(cached)
                    continue
                try:
                    tree = ast.parse(raw, filename=relative)
                    record = describe(relative,tree,digest)
                except (SyntaxError,UnicodeError,ValueError) as error:
                    record = {'path':relative,'digest':digest,'classes':[], 'functions':[],
                              'imports':[], 'error':f'{type(error).__name__} at line {getattr(error,"lineno", "?")}; inspect source'}
                self.cache[relative]=record
                records.append(record)
            except (OSError,ValueError):
                skipped += 1
        inventory = hashlib.sha256(''.join(r['path']+r['digest'] for r in records).encode()).hexdigest()[:16]
        intro = (HEADER + f'Revision: {inventory}. Source files: {len(records)}; skipped/over limit: {skipped}.\n'
                 'Static hints, not runtime truth. @N is the source line. Defaults/bodies may be abbreviated.\n'
                 'Inheritance, dynamic setattr, properties and external object assignments may add fields; absence is not proof.\n'
                 'Inspect the current definition before changing a caller. Map generation never imports project code.\n')
        note_warning = None
        try:
            notes=self.notes.view()
        except (OSError,ValueError):
            notes=[]
            note_warning='Interface notes unavailable or invalid; previous note content is not trusted.'
        intro += f'Model notes: {sum(n["status"]!="stale" for n in notes)} current-at-version, {sum(n["status"]=="stale" for n in notes)} STALE. Semantic claims require source review.\n'
        if note_warning: intro += note_warning+'\n'
        full_parts, compact_parts = [intro], [intro]
        records.sort(key=lambda r:(r['path'] not in self.focus_paths,
                                  r['path'].startswith('tests/') or Path(r['path']).name.startswith('test_'),r['path']))
        for record in records:
            title = f"\n## {record['path']} [sha256:{record['digest'][:12]}]\n"
            body = '\n'.join(record['classes']+record['functions']+record.get('variables',[]))
            semantic=[]
            for note in notes:
                if note['path']==record['path']:
                    label='STALE MODEL NOTE' if note['status']=='stale' else 'MODEL NOTE @ recorded source version'
                    semantic.append(f"{label} {note['symbol']}: {note['note']}" +
                                    (' [changed: '+', '.join(note['changed_sources'])+']' if note['changed_sources'] else ''))
            if record.get('error'): body = record['error']
            if semantic: body += '\n'+'\n'.join(semantic)
            full_parts.append(title + body + '\nImports: '+ '; '.join(record['imports'])+'\n')
            compact_parts.append(title+body+'\n')
        full = ''.join(full_parts)
        context = ''.join(compact_parts)
        if len(context)>context_limit:
            context=context[:context_limit-150]+'\n[Map excerpt truncated. Read PROJECT_MAP.md or the specific source file for omitted interfaces.]'
        target = self.policy.resolve_write('PROJECT_MAP.md')
        warning = note_warning
        written = False
        if target.exists() and not target.read_text(encoding='utf-8').startswith(HEADER):
            warning='Existing user PROJECT_MAP.md left untouched; generated excerpt below is fresh.'
        else:
            # Cap on-disk output as well. Always disclose omissions.
            if len(full)>64000:
                full=full[:63800]+'\n[Map truncated; inspect omitted source definitions directly.]\n'
            if not target.exists() or target.read_text(encoding='utf-8')!=full:
                temporary = None
                try:
                    with tempfile.NamedTemporaryFile(dir=target.parent,prefix='.orchestra-map-',delete=False) as stream:
                        temporary=stream.name
                        stream.write(full.encode('utf-8'))
                    if self.policy.resolve_write('PROJECT_MAP.md')!=target:
                        raise OSError('Map destination changed')
                    os.replace(temporary,target)
                    written=True
                finally:
                    if temporary and os.path.exists(temporary): os.unlink(temporary)
        return {'context':context, 'revision':inventory, 'written':written,
                'files':len(records),'skipped':skipped,'warning':warning,
                'notes_current':sum(n['status']!='stale' for n in notes),
                'notes_stale':sum(n['status']=='stale' for n in notes)}

    def after_edit(self, paths, notes):
        self.focus_paths = list(dict.fromkeys([*paths,*self.focus_paths]))[:8]
        warnings=[]
        saved=0
        try:
            stored=self.notes.save(notes,paths)
            saved=stored['saved']
            warnings.extend(stored['warnings'])
        except (OSError,ValueError):
            warnings.append('Code changed; semantic notes were not saved. Existing notes were preserved.')
        try:
            inventory=self.refresh()
            if inventory['warning']: warnings.append(inventory['warning'])
            return {'updated':True,'revision':inventory['revision'], 'map_file':'PROJECT_MAP.md',
                    'notes_file':'INTERFACE_NOTES.json' if saved or inventory['notes_current'] or inventory['notes_stale'] else None,
                    'notes_saved':saved, 'notes_current':inventory['notes_current'],
                    'notes_stale':inventory['notes_stale'],'warnings':warnings}
        except (OSError,ValueError):
            warnings.append('Code changed; map could not be refreshed. Read source before trusting cached interfaces.')
            return {'updated':False,'notes_saved':saved,'warnings':warnings}
